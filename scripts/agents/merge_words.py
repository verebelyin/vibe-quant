#!/usr/bin/env python3
"""Resolve git conflict hunks with a word-level 3-way merge (stdlib only).

    scripts/agents/merge_words.py <file> [--base REF]

For a file with conflict markers in the current merge (or ``git apply --3way``): each hunk is
merged token by token (words, whitespace, punctuation) against the base version of those
lines, so two edits in different places of one long line (SPEC.md paragraphs) both survive.
Base blob: ``--base REF``, else the index base stage, else ``merge-base(HEAD, MERGE_HEAD)``;
the hunks are regenerated by ``git merge-file --diff3`` and must match the file's own.

Exit 0: file resolved (or had no conflicts; untouched). Exit 1, file left unchanged: two
edits overlap or touch, a base blob is missing, or the hunks do not match the file.
Exit 2: usage.
"""

from __future__ import annotations

import argparse
import difflib
import re
import subprocess
import sys
import tempfile
from pathlib import Path

_TOKEN = re.compile(r"\s+|\w+|[^\w\s]")
Hunk = tuple[str, str, str]  # ours, base, theirs ("" base when the file has none)


class MergeError(Exception):
    """The file is left unchanged; the message says why."""


def _git(cwd: Path, *args: str) -> subprocess.CompletedProcess[str]:
    return subprocess.run(["git", "-C", str(cwd), *args], capture_output=True, text=True)


def _blob(cwd: Path, spec: str) -> str | None:
    proc = _git(cwd, "show", spec)
    return proc.stdout if proc.returncode == 0 else None


def parse(text: str) -> tuple[list[str | int], list[Hunk]]:
    """Split into literal chunks and hunk indices: ``["a\\n", 0, "b\\n"]`` plus the hunks."""
    parts: list[str | int] = []
    hunks: list[Hunk] = []
    plain: list[str] = []
    section: str | None = None
    sides: dict[str, list[str]] = {}
    for line in text.splitlines(keepends=True):
        if section is None:
            if line.startswith("<<<<<<<"):
                parts.append("".join(plain))
                plain = []
                section, sides = "ours", {"ours": [], "base": [], "theirs": []}
            else:
                plain.append(line)
        elif line.startswith("|||||||"):
            section = "base"
        elif line.rstrip("\r\n") == "=======":
            section = "theirs"
        elif line.startswith(">>>>>>>"):
            parts.append(len(hunks))
            hunks.append(("".join(sides["ours"]), "".join(sides["base"]), "".join(sides["theirs"])))
            section = None
        else:
            sides[section].append(line)
    if section is not None:
        raise MergeError("unterminated conflict marker")
    parts.append("".join(plain))
    return parts, hunks


def _edits(base: list[str], other: list[str]) -> list[tuple[int, int, list[str]]]:
    ops = difflib.SequenceMatcher(None, base, other, autojunk=False).get_opcodes()
    return [(i1, i2, other[j1:j2]) for tag, i1, i2, j1, j2 in ops if tag != "equal"]


def merge_hunk(ours: str, base: str, theirs: str) -> str:
    """3-way merge of three texts by tokens; MergeError when two edits overlap or touch."""
    b, o, t = (_TOKEN.findall(s) for s in (base, ours, theirs))
    mine, other = _edits(b, o), _edits(b, t)
    both = [e for e in mine if e in other]  # identical edit on both sides: take it once
    edits = sorted(
        both + [e for e in mine if e not in both] + [e for e in other if e not in both],
        key=lambda e: (e[0], e[1]),
    )
    for prev, cur in zip(edits, edits[1:], strict=False):
        if cur[0] <= prev[1]:
            raise MergeError(f"overlapping edits near base {''.join(b[prev[0] : prev[1]])!r}")
    out: list[str] = []
    pos = 0
    for i1, i2, repl in edits:
        out += b[pos:i1] + repl
        pos = i2
    return "".join(out + b[pos:])


def versions(cwd: Path, name: str, base_ref: str | None) -> tuple[str, str, str]:
    """(ours, base, theirs) whole-file blobs: index stages, else HEAD / MERGE_HEAD."""
    rel = f"./{name}"
    ours = _blob(cwd, f":2:{rel}") or _blob(cwd, f"HEAD:{rel}")
    theirs = _blob(cwd, f":3:{rel}") or _blob(cwd, f"MERGE_HEAD:{rel}")
    if base_ref:
        base = _blob(cwd, f"{base_ref}:{rel}")
    else:
        base = _blob(cwd, f":1:{rel}")
        if base is None:
            mb = _git(cwd, "merge-base", "HEAD", "MERGE_HEAD")
            base = _blob(cwd, f"{mb.stdout.strip()}:{rel}") if mb.returncode == 0 else None
    if ours is None or theirs is None or base is None:
        raise MergeError(f"cannot read the ours/base/theirs versions of {name}")
    return ours, base, theirs


def regenerate(ours: str, base: str, theirs: str) -> list[Hunk]:
    """Conflict hunks of ``git merge-file --diff3`` with their base sections."""
    with tempfile.TemporaryDirectory() as tmp:
        paths = []
        for name, text in (("ours", ours), ("base", base), ("theirs", theirs)):
            p = Path(tmp) / name
            p.write_text(text)
            paths.append(str(p))
        proc = subprocess.run(
            ["git", "merge-file", "-p", "--diff3", *paths], capture_output=True, text=True
        )
    if proc.returncode < 0 or proc.returncode > 127:
        raise MergeError(f"git merge-file failed: {proc.stderr.strip()}")
    return parse(proc.stdout)[1]


def resolve(path: Path, base_ref: str | None = None) -> bool:
    """Rewrite ``path`` with every hunk merged; False when it had no conflicts."""
    parts, hunks = parse(path.read_text())
    if not hunks:
        return False
    regen = regenerate(*versions(path.resolve().parent, path.name, base_ref))
    if [(h[0], h[2]) for h in hunks] != [(h[0], h[2]) for h in regen]:
        raise MergeError("conflict hunks differ from git merge-file's; resolve by hand")
    merged = [merge_hunk(o, b, t) for (o, _, t), (_, b, _) in zip(hunks, regen, strict=True)]
    text = "".join(p if isinstance(p, str) else merged[p] for p in parts)
    path.write_text(text)
    return True


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    ap.add_argument("file", type=Path)
    ap.add_argument("--base", help="ref holding the base version (default: index / merge-base)")
    args = ap.parse_args(argv)
    if not args.file.is_file():
        print(f"merge_words: {args.file}: not a file", file=sys.stderr)
        return 2
    try:
        changed = resolve(args.file, args.base)
    except MergeError as exc:
        print(f"merge_words: {args.file}: {exc}", file=sys.stderr)
        return 1
    print(f"merge_words: {args.file}: {'resolved' if changed else 'no conflicts'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
