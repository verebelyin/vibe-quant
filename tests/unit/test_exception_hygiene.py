"""Ratchet against silently swallowed exceptions in the money packages.

"Fail-open / silently swallowed exception on a money path" was a recurring review
finding (32 of 176 reviews). Detection by eye clearly does not work, so this file
pins today's count per file in ``BASELINE`` and fails when it goes up (a new silent
handler — log it, re-raise it, or narrow it) *and* when it goes down (so the author
lowers the baseline and the ratchet tightens instead of drifting).

A handler counts as "silent" when its body has no ``raise``, no call whose callee
name/attribute looks like logging (``log``/``warning``/``error``/``exception``/
``critical``/``alert``), and every statement is one of: ``pass``, ``...``,
``continue``, ``return``/``return None``/``return <constant>``, or an assignment of
a constant. Anything else (a real call, a re-raise, a non-constant assignment) is
treated as the handler doing something and is not counted.

Keep ``BASELINE`` in sync with the scan: this test is the enforcement point, and the
scanner lives here next to it so both move together.
"""

from __future__ import annotations

import ast
from pathlib import Path
from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from collections.abc import Iterable, Mapping, Sequence

REPO_ROOT = Path(__file__).resolve().parents[2]

#: Money packages (the ones whose exceptions must never vanish). Only directories
#: that exist are scanned, so this tuple is stable if a package is renamed.
SCAN_PACKAGES: tuple[str, ...] = (
    "screening",
    "validation",
    "discovery",
    "overfitting",
    "dsl",
    "risk",
    "paper",
    "data",
    "portfolio",
)

#: Substrings that mark a call as "this handler reports what happened". Matched
#: case-insensitively against the callee's name/attribute.
_LOG_HINTS: tuple[str, ...] = (
    "log",
    "warning",
    "error",
    "exception",
    "critical",
    "alert",
)

#: Today's silent-handler count per file, generated by running ``find_silent_handlers``
#: over every ``.py`` in every existing directory of ``SCAN_PACKAGES``. Lower these as
#: handlers are fixed; never raise one without a written reason in the commit message.
BASELINE: dict[str, int] = {
    "vibe_quant/data/indicator_compute.py": 1,
    "vibe_quant/data/mark_bars.py": 3,
    "vibe_quant/data/verify.py": 1,
    "vibe_quant/discovery/__main__.py": 8,
    "vibe_quant/discovery/campaign.py": 1,
    "vibe_quant/discovery/fitness.py": 1,
    "vibe_quant/discovery/genome.py": 2,
    "vibe_quant/dsl/conditions.py": 1,
    "vibe_quant/dsl/indicators.py": 2,
    "vibe_quant/dsl/translator.py": 1,
    "vibe_quant/overfitting/pipeline.py": 2,
    "vibe_quant/paper/guard.py": 1,
    "vibe_quant/paper/node.py": 1,
    "vibe_quant/portfolio/__main__.py": 1,
    "vibe_quant/screening/__main__.py": 2,
    "vibe_quant/screening/replay_drift.py": 3,
    "vibe_quant/validation/consistency.py": 6,
    "vibe_quant/validation/extraction.py": 9,
}


def _callee_identifier(call: ast.Call) -> str:
    func = call.func
    if isinstance(func, ast.Attribute):
        return func.attr
    if isinstance(func, ast.Name):
        return func.id
    return ""


def _reports(call: ast.Call) -> bool:
    return any(hint in _callee_identifier(call).lower() for hint in _LOG_HINTS)


def _is_silent_statement(stmt: ast.stmt) -> bool:
    if isinstance(stmt, (ast.Pass, ast.Continue)):
        return True
    if isinstance(stmt, ast.Expr):
        return isinstance(stmt.value, ast.Constant)
    if isinstance(stmt, ast.Return):
        return stmt.value is None or isinstance(stmt.value, ast.Constant)
    if isinstance(stmt, ast.Assign):
        return isinstance(stmt.value, ast.Constant)
    return False


def _is_silent_handler(handler: ast.ExceptHandler) -> bool:
    for node in ast.walk(handler):
        if node is handler:
            continue
        if isinstance(node, ast.Raise):
            return False
        if isinstance(node, ast.Call) and _reports(node):
            return False
    return all(_is_silent_statement(stmt) for stmt in handler.body)


def find_silent_handlers(source: str, filename: str = "<string>") -> list[ast.ExceptHandler]:
    """Return every ``except`` handler in ``source`` that swallows its exception."""
    tree = ast.parse(source, filename=filename)
    return [
        node
        for node in ast.walk(tree)
        if isinstance(node, ast.ExceptHandler) and _is_silent_handler(node)
    ]


def _handler_label(handler: ast.ExceptHandler) -> str:
    if handler.type is None:
        return "except:"
    return f"except {ast.unparse(handler.type)}:"


def _scan_package(package: str) -> Iterable[tuple[str, list[ast.ExceptHandler]]]:
    directory = REPO_ROOT / "vibe_quant" / package
    if not directory.is_dir():
        return
    for path in sorted(directory.rglob("*.py")):
        relative = path.relative_to(REPO_ROOT).as_posix()
        yield relative, find_silent_handlers(path.read_text(), relative)


def scan_money_packages() -> dict[str, list[ast.ExceptHandler]]:
    """Map every money-package file with ≥1 silent handler to its handlers."""
    found: dict[str, list[ast.ExceptHandler]] = {}
    for package in SCAN_PACKAGES:
        for relative, handlers in _scan_package(package):
            if handlers:
                found[relative] = handlers
    return found


def ratchet_failures(
    found: Mapping[str, Sequence[ast.ExceptHandler]],
    baseline: Mapping[str, int],
) -> list[str]:
    """Return one message per way the scan drifted from ``baseline``.

    Two drifts are failures: a file with more silent handlers than its baseline (or
    a new file at all), and a file with fewer — the second keeps the ratchet tight,
    because a fixed handler must lower its baseline in the same change.
    """
    regressions: list[str] = []
    for relative, handlers in sorted(found.items()):
        base = baseline.get(relative, 0)
        if len(handlers) <= base:
            continue
        locations = ", ".join(
            f"{relative}:{h.lineno} ({_handler_label(h)})" for h in handlers
        )
        regressions.append(
            f"{relative}: {len(handlers)} silent handler(s), baseline {base} "
            f"[{locations}] — log it, re-raise it, or narrow it"
        )

    loosenings: list[str] = []
    for relative, base in sorted(baseline.items()):
        count = len(found.get(relative, ()))
        if count < base:
            loosenings.append(
                f"{relative}: {count} silent handler(s), baseline {base} — "
                f"lower BASELINE[{relative!r}] to {count} so the ratchet tightens"
            )

    return regressions + loosenings


def test_silent_exception_ratchet() -> None:
    failures = ratchet_failures(scan_money_packages(), BASELINE)
    assert not failures, "silent-exception ratchet drifted:\n  " + "\n  ".join(failures)


def test_ratchet_flags_a_new_silent_handler() -> None:
    found = {"vibe_quant/paper/node.py": find_silent_handlers(
        "try:\n    book()\nexcept Exception:\n    pass\n", "x.py"
    )}
    failures = ratchet_failures(found, {"vibe_quant/paper/node.py": 0})
    assert len(failures) == 1
    assert "log it, re-raise it, or narrow it" in failures[0]
    assert "vibe_quant/paper/node.py:3" in failures[0]


def test_ratchet_flags_a_stale_baseline() -> None:
    failures = ratchet_failures({}, {"vibe_quant/paper/node.py": 2})
    assert len(failures) == 1
    assert "lower BASELINE['vibe_quant/paper/node.py'] to 0" in failures[0]


def test_scanner_flags_synthetic_silent_handler() -> None:
    source = "try:\n    risky()\nexcept Exception:\n    pass\n"
    handlers = find_silent_handlers(source)
    assert len(handlers) == 1
    assert _handler_label(handlers[0]) == "except Exception:"


def test_scanner_ignores_reporting_handler() -> None:
    source = "try:\n    risky()\nexcept ValueError:\n    logger.warning('nope')\n"
    assert find_silent_handlers(source) == []


def test_scanner_ignores_reraising_handler() -> None:
    source = "try:\n    risky()\nexcept ValueError:\n    raise\n"
    assert find_silent_handlers(source) == []
