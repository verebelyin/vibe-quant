def _callee_identifier(call: ast.Call) -> str:
    func = call.func
    if isinstance(func, ast.Attribute):
        return func.attr
    if isinstance(func, ast.Name):
        return func.id
    return ""


def _reports(call: ast.Call) -> bool:
    return any(hint in _callee_identifier(call).lower() for hint in _LOG_HINTS)


def _is_silent_statement(stmt: ast.stmt) -> bool:
    if isinstance(stmt, (ast.Pass, ast.Continue)):
        return True
    if isinstance(stmt, ast.Expr):
        return isinstance(stmt.value, ast.Constant)
    if isinstance(stmt, ast.Return):
        return stmt.value is None or isinstance(stmt.value, ast.Constant)
    if isinstance(stmt, ast.Assign):
        return isinstance(stmt.value, ast.Constant)
    return False


def _is_silent_handler(handler: ast.ExceptHandler) -> bool:
    for node in ast.walk(handler):
        if node is handler:
            continue
        if isinstance(node, ast.Raise):
            return False
        if isinstance(node, ast.Call) and _reports(node):
            return False
    return all(_is_silent_statement(stmt) for stmt in handler.body)


def find_silent_handlers(source: str, filename: str = "<string>") -> list[ast.ExceptHandler]:
    """Return every ``except`` handler in ``source`` that swallows its exception."""
    tree = ast.parse(source, filename=filename)
    return [
        node
        for node in ast.walk(tree)
        if isinstance(node, ast.ExceptHandler) and _is_silent_handler(node)
    ]


def _handler_label(handler: ast.ExceptHandler) -> str:
    if handler.type is None:
        return "except:"
    return f"except {ast.unparse(handler.type)}:"


class Swallow(NamedTuple):
    """One place an exception can vanish, with the source line and a human label."""

    lineno: int
    label: str


def _is_broad_handler(handler: ast.ExceptHandler) -> bool:
    """True for a bare ``except`` or one naming ``Exception``/``BaseException``.

    Handles the two spellings the scanner has to see through: the name used directly
    (``Exception``), as an attribute (``builtins.Exception``) and inside a tuple
    (``except (OSError, Exception):``).
    """
    kind = handler.type
    if kind is None:
        return True
    names = kind.elts if isinstance(kind, ast.Tuple) else [kind]
    for name in names:
        identifier = name.attr if isinstance(name, ast.Attribute) else getattr(name, "id", "")
        if identifier in _BROAD_EXCEPTIONS:
            return True
    return False


def _reports_or_raises(handler: ast.ExceptHandler) -> bool:
    """True when the handler logs what happened or re-raises at all (anywhere in body)."""
    for node in ast.walk(handler):
        if node is handler:
            continue
        if isinstance(node, ast.Raise):
            return True
        if isinstance(node, ast.Call) and _reports(node):
            return True
    return False


def _is_suppress_item(item: ast.withitem) -> bool:
    """True for ``with contextlib.suppress(...):`` (any expression calling ``suppress``)."""
    expr = item.context_expr
    if not isinstance(expr, ast.Call):
        return False
    func = expr.func
    name = func.attr if isinstance(func, ast.Attribute) else getattr(func, "id", "")
    return name == "suppress"


def find_swallows(source: str, filename: str = "<string>") -> list[Swallow]:
    """Return every place ``source`` can swallow an exception without a trace.

    Three shapes count: today's silent handlers, broad handlers that do something but
    neither log nor re-raise, and every ``with contextlib.suppress(...)`` block.
    """
    tree = ast.parse(source, filename=filename)
    swallows: list[Swallow] = []
    for node in ast.walk(tree):
        if isinstance(node, ast.ExceptHandler):
            if _is_silent_handler(node):
                swallows.append(Swallow(node.lineno, _handler_label(node)))
            elif _is_broad_handler(node) and not _reports_or_raises(node):
                swallows.append(Swallow(node.lineno, f"{_handler_label(node)} (no log)"))
        elif isinstance(node, (ast.With, ast.AsyncWith)):
            for item in node.items:
                if _is_suppress_item(item):
                    swallows.append(Swallow(node.lineno, ast.unparse(item.context_expr)))
    return sorted(swallows)


def _scan_package(package: str) -> Iterable[tuple[str, list[Swallow]]]:
    directory = REPO_ROOT / "vibe_quant" / package
    if not directory.is_dir():
        return
    for path in sorted(directory.rglob("*.py")):
        relative = path.relative_to(REPO_ROOT).as_posix()
        yield relative, find_swallows(path.read_text(), relative)


def _scan_root_file(name: str) -> Iterable[tuple[str, list[Swallow]]]:
    path = REPO_ROOT / "vibe_quant" / name
    if not path.is_file():
        return
    relative = path.relative_to(REPO_ROOT).as_posix()
    yield relative, find_swallows(path.read_text(), relative)


def scan_money_packages() -> dict[str, list[Swallow]]:
    """Map every money-package or root-module file with ≥1 swallow to its swallows."""
    found: dict[str, list[Swallow]] = {}
    for package in SCAN_PACKAGES:
        for relative, swallows in _scan_package(package):
            if swallows:
                found[relative] = swallows
    for name in SCAN_FILES:
        for relative, swallows in _scan_root_file(name):
            if swallows:
                found[relative] = swallows
    return found


def ratchet_failures(
    found: Mapping[str, Sequence[Swallow]],
    baseline: Mapping[str, int],
) -> list[str]:
    """Return one message per way the scan drifted from ``baseline``.

    Two drifts are failures: a file with more swallows than its baseline (or a new
    file at all), and a file with fewer — the second keeps the ratchet tight, because
    a fixed swallow must lower its baseline in the same change.
    """
    regressions: list[str] = []
    for relative, handles in sorted(found.items()):
        base = baseline.get(relative, 0)
        if len(handles) <= base:
            continue
        locations = ", ".join(
            f"{relative}:{s.lineno} ({s.label})" for s in handles
        )
        regressions.append(
            f"{relative}: {len(handles)} silent handler(s), baseline {base} "
            f"[{locations}] — log it, re-raise it, or narrow it"
        )

    loosenings: list[str] = []
    for relative, base in sorted(baseline.items()):
        count = len(found.get(relative, ()))
        if count < base:
            loosenings.append(
                f"{relative}: {count} silent handler(s), baseline {base} — "
                f"lower BASELINE[{relative!r}] to {count} so the ratchet tightens"
            )

    return regressions + loosenings


def test_silent_exception_ratchet() -> None:
    failures = ratchet_failures(scan_money_packages(), BASELINE)
    assert not failures, "silent-exception ratchet drifted:\n  " + "\n  ".join(failures)


def test_ratchet_flags_a_new_silent_handler() -> None:
    found = {"vibe_quant/paper/node.py": find_swallows(
        "try:\n    book()\nexcept Exception:\n    pass\n", "x.py"
    )}
    failures = ratchet_failures(found, {"vibe_quant/paper/node.py": 0})
    assert len(failures) == 1
    assert "log it, re-raise it, or narrow it" in failures[0]
    assert "vibe_quant/paper/node.py:3" in failures[0]


def test_ratchet_flags_a_stale_baseline() -> None:
    failures = ratchet_failures({}, {"vibe_quant/paper/node.py": 2})
    assert len(failures) == 1
    assert "lower BASELINE['vibe_quant/paper/node.py'] to 0" in failures[0]


def test_scanner_flags_synthetic_silent_handler() -> None:
    source = "try:\n    risky()\nexcept Exception:\n    pass\n"
    handlers = find_silent_handlers(source)
    assert len(handlers) == 1
    assert _handler_label(handlers[0]) == "except Exception:"


def test_scanner_ignores_reporting_handler() -> None:
    source = "try:\n    risky()\nexcept ValueError:\n    logger.warning('nope')\n"
    assert find_silent_handlers(source) == []


def test_scanner_ignores_reraising_handler() -> None:
    source = "try:\n    risky()\nexcept ValueError:\n    raise\n"
    assert find_silent_handlers(source) == []


def test_scanner_flags_suppress() -> None:
    source = "with contextlib.suppress(Exception):\n    risky()\n"
    swallows = find_swallows(source)
    assert len(swallows) == 1
    assert swallows[0].label == "contextlib.suppress(Exception)"


def test_scanner_flags_broad_unlogged_handler() -> None:
    source = "try:\n    risky()\nexcept Exception as e:\n    r = f(e)\n"
    swallows = find_swallows(source)
    assert len(swallows) == 1
    assert swallows[0].label == "except Exception: (no log)"


def test_scanner_flags_broad_unlogged_tuple_handler() -> None:
    """``Exception`` inside a tuple still makes the handler broad (unlogged)."""
    source = "try:\n    f()\nexcept (OSError, Exception) as e:\n    r = g(e)\n"
    swallows = find_swallows(source)
    assert len(swallows) == 1
    assert swallows[0].label == "except (OSError, Exception): (no log)"


def test_scanner_ignores_broad_handler_with_debug_log() -> None:
    source = "try:\n    risky()\nexcept Exception as e:\n    logger.debug('x %s', e)\n"
    assert find_swallows(source) == []


def test_scanner_counts_bare_except() -> None:
    source = "try:\n    risky()\nexcept:\n    cleanup()\n"
    swallows = find_swallows(source)
    assert len(swallows) == 1
    assert swallows[0].label == "except: (no log)"


def test_scanner_ignores_narrow_working_handler() -> None:
    source = "try:\n    risky()\nexcept ValueError:\n    x = f()\n"
    assert find_swallows(source) == []


def test_root_scan_files_are_ratcheted(
    monkeypatch: pytest.MonkeyPatch, tmp_path: Path
) -> None:
    """A swallow in a root module is found by the scan, so its baseline can pin it."""
    (tmp_path / "vibe_quant").mkdir()
    (tmp_path / "vibe_quant" / "trade_ledger.py").write_text(
        "try:\n    risky()\nexcept Exception:\n    pass\n"
    )
    monkeypatch.setattr(sys.modules[__name__], "REPO_ROOT", tmp_path)
    found = scan_money_packages()
    assert list(found) == ["vibe_quant/trade_ledger.py"]


def test_l4_moved_no_swallow_across_the_touched_files() -> None:
    """r3 F10: L4 moves handlers; the touched files' total must not change (1 + 5 + 0)."""
    found = scan_money_packages()
    touched = (
        "vibe_quant/screening/nt_runner.py",
        "vibe_quant/validation/extraction.py",
        "vibe_quant/trade_ledger.py",
    )
    assert sum(len(found.get(path, ())) for path in touched) == 6
    assert "vibe_quant/trade_ledger.py" not in found
    assert BASELINE["vibe_quant/trade_ledger.py"] == 0
