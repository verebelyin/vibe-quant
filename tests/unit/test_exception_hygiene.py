"""Ratchet against silently swallowed exceptions in the money packages.

"Fail-open / silently swallowed exception on a money path" was a recurring review
finding (32 of 176 reviews). Detection by eye clearly does not work, so this file
pins today's count per file in ``BASELINE`` and fails when it goes up (a new silent
handler — log it, re-raise it, or narrow it) *and* when it goes down (so the author
lowers the baseline and the ratchet tightens instead of drifting).

A handler counts as "silent" when its body has no ``raise``, no call whose callee
name/attribute looks like logging (``log``/``warning``/``error``/``exception``/
``critical``/``alert``/``debug``/``info``), and every statement is one of: ``pass``,
``...``, ``continue``, ``return``/``return None``/``return <constant>``, or an
assignment of a constant. Anything else (a real call, a re-raise, a non-constant
assignment) is treated as the handler doing something and is not counted.

``find_swallows`` widens the net to the two blind spots a silent-handler-only scan
misses: a *broad* handler (bare ``except``, ``Exception``/``BaseException`` by name,
attribute or inside a tuple) that does something but neither logs nor re-raises, and
every ``with contextlib.suppress(...)`` block. Both swallow an exception just as
quietly, so they feed the same ratchet.

Keep ``BASELINE`` in sync with the scan: this test is the enforcement point, and the
scanner lives here next to it so both move together.
"""

from __future__ import annotations

